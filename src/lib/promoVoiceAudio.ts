/**
 * Bundled audio for the four fixed Upgrade Plan promotional samples.
 *
 * These clips never change at runtime, so they ship with the app instead of
 * being generated on demand. That is what makes the first tap immediate on a
 * fresh install and offline: there is no request, no generation, no download and
 * no credit to spend — the file is already on the device.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * THE MAP BELOW IS GENERATED. Do not hand-edit it.
 *
 *   npm run generate:promo-voice
 *
 * The script writes the `PROMO_SAMPLE_AUDIO` literal between the two markers
 * from `PROMO_SAMPLE_TEXT` and the files it produced, so the map, the assets and
 * the spoken words cannot drift apart. Everything outside the markers is
 * hand-written and is preserved across regenerations.
 *
 * Until the script has run the map is empty, which is deliberate: `require()`ing
 * an asset that does not exist fails the Metro bundle, so an ungenerated build
 * must contain no entries at all. An empty map simply means every lookup misses
 * and `speakPromoSample` uses the existing `/v1/voice/promo` route, exactly as
 * it did before bundling — see the dev warning there.
 *
 * The generated version marker adds the same protection after pronunciation
 * or content changes: an older complete map remains buildable but is ignored
 * until the generator rewrites all clips and stamps the current promo version.
 * ────────────────────────────────────────────────────────────────────────────
 *
 * Every entry is a literal `require()` of a literal path. Nothing here is built
 * from a variable: Metro resolves asset references statically, so a computed
 * path would silently produce no asset at all.
 *
 * Pure module: no react-native and no expo imports, so it is unit-testable. A
 * `require()`d asset is a module id — a number — which is what `expo-audio`
 * accepts as an `AudioSource`.
 */

