/**
 * The bundled clip for a sample in the requested language, or null.
 *
 * Language resolution is `resolvePromoLang`'s and nobody else's, so the audio
 * that plays is the audio for the words on screen. Unsupported input has already
 * resolved to `en`. A missing clip for a supported language returns null so the
 * network route can fetch that language; it must never substitute an English
 * bundle beneath localized text.
 */
export function bundledPromoAudio(
  sample: PromoSampleId,
  langCode: string | undefined,
): number | null {
  if (PROMO_SAMPLE_AUDIO_VERSION !== PROMO_SAMPLE_VERSION) return null;
  const lang = resolvePromoLang(langCode);
  return PROMO_SAMPLE_AUDIO[lang]?.[sample] ?? null;
}

/** Every bundled clip for one language, for preparing them together. */
export function bundledPromoAudioSet(langCode: string | undefined): readonly number[] {
  if (PROMO_SAMPLE_AUDIO_VERSION !== PROMO_SAMPLE_VERSION) return [];
  const lang = resolvePromoLang(langCode);
  const set = PROMO_SAMPLE_AUDIO[lang];
  return set ? Object.values(set) : [];
}
